-- 1. Tabel akun
CREATE TABLE public.accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code VARCHAR(20) NOT NULL UNIQUE,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(30) NOT NULL
        CHECK (
            account_type IN (
                'ASSET',
                'LIABILITY',
                'EQUITY',
                'REVENUE',
                'EXPENSE'
            )
        ),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. Tabel voucher kas keluar
CREATE TABLE public.cash_vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_number VARCHAR(50) NOT NULL UNIQUE,
    transaction_date DATE NOT NULL,
    payee VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'POSTED')),
    created_by UUID REFERENCES auth.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    posted_by UUID REFERENCES auth.users(id) ON DELETE RESTRICT,
    posted_at TIMESTAMPTZ,
    reversal_of BIGINT REFERENCES public.cash_vouchers(id)
        ON DELETE RESTRICT,
    content_hash TEXT,
    CONSTRAINT cash_vouchers_posting_check CHECK (
        (status = 'DRAFT' AND posted_at IS NULL AND posted_by IS NULL)
        OR
        (status = 'POSTED' AND posted_at IS NOT NULL AND posted_by IS NOT NULL)
    ),
    CONSTRAINT cash_vouchers_reversal_check CHECK (
        reversal_of IS NULL OR reversal_of <> id
    ),
    CONSTRAINT cash_vouchers_reversal_unique UNIQUE (reversal_of)
);

-- 3. Tabel rincian jurnal voucher
CREATE TABLE public.cash_voucher_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL
        REFERENCES public.cash_vouchers(id) ON DELETE RESTRICT,
    line_number INTEGER NOT NULL CHECK (line_number > 0),
    account_id BIGINT NOT NULL
        REFERENCES public.accounts(id) ON DELETE RESTRICT,
    debit NUMERIC NOT NULL DEFAULT 0,
    credit NUMERIC NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT voucher_lines_amount_nonnegative
        CHECK (debit >= 0 AND credit >= 0),
    CONSTRAINT voucher_lines_one_side_only
        CHECK (
            (debit > 0 AND credit = 0)
            OR
            (credit > 0 AND debit = 0)
        ),
    CONSTRAINT voucher_lines_number_unique
        UNIQUE (voucher_id, line_number)
);

-- 4. Tabel audit trail
CREATE TABLE public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT
        REFERENCES public.cash_vouchers(id) ON DELETE RESTRICT,
    actor_id UUID REFERENCES auth.users(id) ON DELETE RESTRICT,
    action VARCHAR(30) NOT NULL
        CHECK (
            action IN (
                'CREATE',
                'UPDATE',
                'POST',
                'REVERSAL',
                'REJECTED'
            )
        ),
    event_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    previous_hash TEXT,
    event_hash TEXT
);

